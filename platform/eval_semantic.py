#!/usr/bin/env python3
"""
Evaluation harness — does Moss semantic recall catch clawbacks the regex library
misses, without flagging ordinary EOB lines, fast enough to stay on the hot path?

WHAT IT MEASURES
----------------
1. Detection quality   precision / recall / F1 with bootstrap 95% confidence
                       intervals, baseline (regex) vs regex + Moss.
2. Operating point     a full threshold sweep, with the chosen threshold picked
                       by a stated rule rather than by eyeball.
3. Latency             warm-up discarded, and Moss's in-engine time reported
                       separately from this integration's thread-hop overhead,
                       plus a concurrent-load phase matching the WebSocket path.
4. Document level      whole-EOB detection, including offsets split across two
                       lines — the case the money-gate pre-filter handles worst.
5. Breakdown           per category and per rendering style, so a headline
                       number cannot hide a cluster the system never solves.

METHOD
------
The eval set is generated by `eval_data.py` and is held out from the indexed
corpus — `assert_disjoint_from_corpus()` fails the run on exact or near-duplicate
overlap, so the split cannot rot silently as either file is edited.

The threshold sweep queries Moss once per line via `SemanticMatcher.probe()`,
which returns the raw top hit without applying the label/threshold filter. Every
candidate threshold is then evaluated offline against those stored scores. This
is both far cheaper than re-querying per threshold and strictly more correct:
every point on the curve sees identical retrieval.

Usage:
    python eval_semantic.py                 # full report
    python eval_semantic.py --json out.json
    python eval_semantic.py --stub          # exercise the harness without Moss
    python eval_semantic.py --precision-floor 0.98
"""

from __future__ import annotations

import argparse
import json
import os
import random
import statistics
import sys
import threading
import time
from dataclasses import asdict, dataclass
from typing import Dict, List, Optional, Tuple

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests"))

import eval_data
from eval_data import EvalDocument, EvalLine

WARMUP_QUERIES = 10          # discarded: first queries pay one-off costs
BOOTSTRAP_ROUNDS = 2000
BOOTSTRAP_SEED = 20260917
DEFAULT_PRECISION_FLOOR = 0.95
SWEEP_STEPS = [round(x * 0.025, 3) for x in range(0, 41)]   # 0.000 → 1.000


# ── metrics ───────────────────────────────────────────────────────────────────

def _prf(tp: int, fp: int, fn: int, tn: int) -> Dict[str, float]:
    precision = tp / (tp + fp) if (tp + fp) else 1.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) else 0.0
    total = tp + fp + fn + tn
    return {
        "precision": round(precision, 4),
        "recall": round(recall, 4),
        "f1": round(f1, 4),
        "accuracy": round((tp + tn) / total, 4) if total else 0.0,
        "true_positives": tp, "false_positives": fp,
        "false_negatives": fn, "true_negatives": tn,
    }


def _confusion(pairs: List[Tuple[bool, bool]]) -> Dict[str, float]:
    """pairs of (truth, predicted)."""
    tp = sum(1 for t, p in pairs if t and p)
    fp = sum(1 for t, p in pairs if not t and p)
    fn = sum(1 for t, p in pairs if t and not p)
    tn = sum(1 for t, p in pairs if not t and not p)
    return _prf(tp, fp, fn, tn)


def _bootstrap_ci(pairs: List[Tuple[bool, bool]],
                  rounds: int = BOOTSTRAP_ROUNDS) -> Dict[str, Tuple[float, float]]:
    """
    Percentile bootstrap 95% intervals.

    At this sample size a single flipped line moves recall by a full percentage
    point, so a bare point estimate overstates how much the number is known.
    """
    rng = random.Random(BOOTSTRAP_SEED)
    n = len(pairs)
    if n == 0:
        return {}
    draws = {"precision": [], "recall": [], "f1": []}
    for _ in range(rounds):
        sample = [pairs[rng.randrange(n)] for _ in range(n)]
        m = _confusion(sample)
        for k in draws:
            draws[k].append(m[k])
    out = {}
    for k, vals in draws.items():
        vals.sort()
        lo = vals[int(0.025 * (len(vals) - 1))]
        hi = vals[int(0.975 * (len(vals) - 1))]
        out[k] = (round(lo, 4), round(hi, 4))
    return out


# ── observation collection ────────────────────────────────────────────────────

@dataclass
class LineObservation:
    line: EvalLine
    regex_detected: bool
    gated_out: bool                  # money-gate skipped the semantic query
    probe: Optional[Dict]            # raw Moss top hit, threshold not applied


def collect(lines: List[EvalLine], matcher) -> List[LineObservation]:
    """
    One pass: regex verdict plus the raw Moss top hit for every line.

    Mirrors `_detect_flags` exactly — regex first, money gate second, semantic
    query only on what survives both — so the sweep reflects production
    behaviour rather than an idealised path.
    """
    from agents.recoupment_agent import (_detect_flags, _extract_amounts,
                                         _load_compiled_patterns)

    compiled = _load_compiled_patterns()
    observations: List[LineObservation] = []

    for ev in lines:
        regex_flags = _detect_flags(ev.text, compiled, matcher=None)
        regex_detected = bool(regex_flags)

        gated_out = False
        probe = None
        if not regex_detected:
            if not _extract_amounts(ev.text):
                gated_out = True
            elif matcher is not None and matcher.ready:
                probe = matcher.probe(ev.text)

        observations.append(LineObservation(ev, regex_detected, gated_out, probe))
    return observations


def decide(obs: LineObservation, threshold: float, use_semantic: bool) -> bool:
    if obs.regex_detected:
        return True
    if not use_semantic or obs.probe is None:
        return False
    return obs.probe["label"] == "recoupment" and obs.probe["score"] >= threshold


def pairs_at(observations: List[LineObservation], threshold: float,
             use_semantic: bool) -> List[Tuple[bool, bool]]:
    return [(o.line.is_recoupment, decide(o, threshold, use_semantic))
            for o in observations]


# ── threshold sweep ───────────────────────────────────────────────────────────

def sweep(observations: List[LineObservation]) -> List[Dict]:
    rows = []
    for t in SWEEP_STEPS:
        m = _confusion(pairs_at(observations, t, use_semantic=True))
        rows.append({"threshold": t, **m})
    return rows


def choose_operating_point(rows: List[Dict],
                           precision_floor: float) -> Optional[Dict]:
    """
    Maximise recall subject to precision >= floor; break ties on precision.

    Recall bought with precision is not a win in this product. A coordinator who
    gets a wall of false flags per EOB stops reading them, and the missed
    clawback the system exists to catch goes out with the noise. So precision is
    a constraint and recall is the objective, rather than optimising F1, which
    would happily trade away precision the workflow cannot afford to lose.
    """
    eligible = [r for r in rows if r["precision"] >= precision_floor]
    if not eligible:
        return None
    return max(eligible, key=lambda r: (r["recall"], r["precision"]))


# ── latency ───────────────────────────────────────────────────────────────────

def latency_report(observations: List[LineObservation]) -> Dict:
    """End-to-end vs Moss in-engine time, warm-up discarded."""
    e2e = [o.probe["query_ms"] for o in observations if o.probe]
    engine = [o.probe["engine_ms"] for o in observations
              if o.probe and o.probe.get("engine_ms") is not None]
    e2e, engine = e2e[WARMUP_QUERIES:], engine[WARMUP_QUERIES:]

    def pct(vals: List[float], p: float) -> Optional[float]:
        if not vals:
            return None
        s = sorted(vals)
        return round(s[min(len(s) - 1, int(round(p * (len(s) - 1))))], 3)

    report = {
        "samples": len(e2e),
        "warmup_discarded": WARMUP_QUERIES,
        "end_to_end_ms": {"p50": pct(e2e, .50), "p95": pct(e2e, .95),
                          "p99": pct(e2e, .99), "max": pct(e2e, 1.0)},
    }
    if engine:
        report["moss_engine_ms"] = {"p50": pct(engine, .50), "p95": pct(engine, .95)}
        if report["end_to_end_ms"]["p50"] is not None:
            report["bridge_overhead_ms_p50"] = round(
                report["end_to_end_ms"]["p50"] - report["moss_engine_ms"]["p50"], 3)
    return report


def concurrent_latency(matcher, lines: List[EvalLine],
                       threads: int = 8, per_thread: int = 25) -> Dict:
    """
    Latency under concurrent load, which is the real production condition: the
    orchestrator runs in worker threads off the WebSocket path, so queries
    overlap. Also checks that telemetry counters survive the concurrency —
    `queries += 1` from N threads loses updates without a lock.
    """
    if not matcher or not matcher.ready:
        return {"skipped": "matcher not ready"}

    sample = [l.text for l in lines if l.text][:per_thread]
    matcher.reset_stats()
    timings: List[float] = []
    errors: List[str] = []
    lock = threading.Lock()

    def worker() -> None:
        local: List[float] = []
        try:
            for text in sample:
                t0 = time.perf_counter()
                matcher.match(text)
                local.append((time.perf_counter() - t0) * 1000.0)
        except Exception as exc:                      # pragma: no cover
            with lock:
                errors.append(f"{type(exc).__name__}: {exc}")
        with lock:
            timings.extend(local)

    workers = [threading.Thread(target=worker) for _ in range(threads)]
    started = time.perf_counter()
    for w in workers:
        w.start()
    for w in workers:
        w.join()
    wall = (time.perf_counter() - started) * 1000.0

    s = sorted(timings)
    def pct(p: float) -> Optional[float]:
        return round(s[min(len(s) - 1, int(round(p * (len(s) - 1))))], 3) if s else None

    expected = threads * len(sample)
    observed = matcher.stats()["queries"]
    return {
        "threads": threads, "queries_issued": len(timings),
        "wall_ms": round(wall, 1),
        "p50_ms": pct(.50), "p95_ms": pct(.95), "p99_ms": pct(.99),
        "throughput_qps": round(len(timings) / (wall / 1000.0), 1) if wall else None,
        "counter_expected": expected, "counter_observed": observed,
        "counter_intact": expected == observed,
        "errors": errors,
    }


# ── document level ────────────────────────────────────────────────────────────

def document_eval(docs: List[EvalDocument], matcher, threshold: Optional[float]) -> Dict:
    """Whole-EOB detection, with split-across-lines offsets tracked separately."""
    from agents.recoupment_agent import RecoupmentAgent

    if matcher is not None and threshold is not None:
        matcher.threshold = threshold

    results = {}
    for label, agent in (("baseline", RecoupmentAgent(use_semantic=False)),
                         ("with_moss", RecoupmentAgent(matcher=matcher)
                          if matcher and matcher.ready else None)):
        if agent is None:
            continue
        pairs, split_hits, split_total = [], 0, 0
        for doc in docs:
            detected = bool(agent.run(doc.text, doc.name).flags)
            pairs.append((doc.contains_recoupment, detected))
            if doc.split_across_lines:
                split_total += 1
                split_hits += int(detected)
        results[label] = {
            **_confusion(pairs),
            "split_line_detected": split_hits,
            "split_line_total": split_total,
        }
    return results


# ── breakdown ─────────────────────────────────────────────────────────────────

def breakdown(observations: List[LineObservation], threshold: float,
              key: str) -> List[Dict]:
    groups: Dict[str, List[Tuple[bool, bool]]] = {}
    for o in observations:
        g = getattr(o.line, key)
        groups.setdefault(g, []).append(
            (o.line.is_recoupment, decide(o, threshold, True)))
    rows = []
    for g, pairs in sorted(groups.items()):
        m = _confusion(pairs)
        rows.append({key: g, "n": len(pairs), "recall": m["recall"],
                     "precision": m["precision"]})
    return rows


# ── reporting ─────────────────────────────────────────────────────────────────

def _fmt_ci(point: float, ci: Optional[Tuple[float, float]]) -> str:
    if not ci:
        return f"{point:.3f}"
    return f"{point:.3f} [{ci[0]:.3f}–{ci[1]:.3f}]"


def main() -> int:
    ap = argparse.ArgumentParser(description="Evaluate Moss semantic recall")
    ap.add_argument("--json", dest="json_out")
    ap.add_argument("--stub", action="store_true",
                    help="run against the stub transport (plumbing check only)")
    ap.add_argument("--precision-floor", type=float, default=DEFAULT_PRECISION_FLOOR)
    ap.add_argument("--alpha", type=float)
    ap.add_argument("--no-concurrency", action="store_true")
    args = ap.parse_args()

    if args.alpha is not None:
        os.environ["MOSS_ALPHA"] = str(args.alpha)

    print()
    print("=" * 78)
    print("  RemitGuard — recoupment detection evaluation")
    print("=" * 78)

    # ── dataset ──────────────────────────────────────────────────────────────
    eval_data.assert_disjoint_from_corpus()
    lines = eval_data.build_eval_set()
    docs = eval_data.build_document_set()
    n_pos = sum(1 for l in lines if l.is_recoupment)
    _ov = eval_data.overlap_report()
    worst = max(r["max_overlap"] for r in _ov if r["bank"] in ("novel", "benign"))
    print(f"\n  Lines      {len(lines)}  ({n_pos} clawback / {len(lines)-n_pos} benign)")
    print(f"  Documents  {len(docs)}  ({sum(d.contains_recoupment for d in docs)} positive, "
          f"{sum(d.split_across_lines for d in docs)} with split-line offsets)")
    print(f"  Held out   max token overlap vs indexed corpus (novel+benign banks) "
          f"{worst:.2f} / ceiling {eval_data.MAX_CORPUS_OVERLAP:.2f} ✓")

    # ── matcher ──────────────────────────────────────────────────────────────
    from agents.semantic_matcher import SemanticMatcher, get_matcher, reset_matcher

    matcher = None
    mode = "regex-only"
    if args.stub:
        from stub_moss import StubMossClient
        matcher = SemanticMatcher(client=StubMossClient(), threshold=0.0)
        reset_matcher(matcher)
        if matcher.warm():
            mode = "STUB"
            print("\n  ⚠  STUB MODE — token-overlap similarity, not Moss embeddings.")
            print("     Verifies the harness executes. Numbers are NOT results.")
    else:
        matcher = get_matcher()
        if matcher.enabled and matcher.warm():
            mode = "Moss"
            print(f"\n  Moss index '{matcher.index_name}' ready "
                  f"({matcher.stats()['corpus_size']} phrases)")
        else:
            print(f"\n  ⚠  Moss unavailable — {matcher.disabled_reason}")
            print("     Reporting the regex-only baseline.")
            matcher = None

    results: Dict = {"mode": mode, "n_lines": len(lines), "n_docs": len(docs),
                     "max_corpus_overlap": worst}

    # ── collection ───────────────────────────────────────────────────────────
    print(f"\n  Collecting observations ({len(lines)} lines)...")
    observations = collect(lines, matcher)
    gated = sum(1 for o in observations if o.gated_out)
    queried = sum(1 for o in observations if o.probe)
    print(f"    regex hits {sum(1 for o in observations if o.regex_detected)}"
          f"   money-gated {gated}   Moss queries {queried}")

    # ── baseline ─────────────────────────────────────────────────────────────
    base_pairs = pairs_at(observations, 0.0, use_semantic=False)
    base = _confusion(base_pairs)
    base_ci = _bootstrap_ci(base_pairs)
    results["baseline"] = {**base, "ci95": {k: list(v) for k, v in base_ci.items()}}

    print("\n" + "─" * 78)
    print("  LINE-LEVEL DETECTION          (point estimate [95% bootstrap CI])")
    print("─" * 78)
    print(f"  baseline (regex)   precision {_fmt_ci(base['precision'], base_ci.get('precision'))}"
          f"   recall {_fmt_ci(base['recall'], base_ci.get('recall'))}")
    print(f"                     FN={base['false_negatives']}/{n_pos} clawbacks missed")

    chosen = None
    if matcher and matcher.ready:
        rows = sweep(observations)
        results["sweep"] = rows
        chosen = choose_operating_point(rows, args.precision_floor)
        results["precision_floor"] = args.precision_floor

        if chosen is None:
            print(f"\n  ⚠  No threshold reaches precision ≥ {args.precision_floor:.2f}.")
            best_f1 = max(rows, key=lambda r: r["f1"])
            print(f"     Best F1 {best_f1['f1']:.3f} at threshold {best_f1['threshold']:.3f} "
                  f"(precision {best_f1['precision']:.3f})")
            chosen = best_f1
            results["operating_point_note"] = "precision floor unreachable; used best F1"

        t = chosen["threshold"]
        sem_pairs = pairs_at(observations, t, use_semantic=True)
        sem = _confusion(sem_pairs)
        sem_ci = _bootstrap_ci(sem_pairs)
        results["with_moss"] = {**sem, "threshold": t,
                                "ci95": {k: list(v) for k, v in sem_ci.items()}}

        print(f"  + Moss @ t={t:.3f}    precision {_fmt_ci(sem['precision'], sem_ci.get('precision'))}"
              f"   recall {_fmt_ci(sem['recall'], sem_ci.get('recall'))}")
        caught = base["false_negatives"] - sem["false_negatives"]
        print(f"\n  Δ recall  {sem['recall'] - base['recall']:+.3f}   "
              f"({caught} clawback(s) the regex library missed)")
        print(f"  Δ precision {sem['precision'] - base['precision']:+.3f}")

        # ── sweep table ──────────────────────────────────────────────────────
        print("\n" + "─" * 78)
        print(f"  THRESHOLD SWEEP   (operating rule: max recall s.t. precision ≥ "
              f"{args.precision_floor:.2f})")
        print("─" * 78)
        print("    thresh   precision   recall      f1     FP   FN")
        shown = [r for r in rows if r["threshold"] % 0.1 < 1e-9] or rows[::4]
        for r in shown:
            mark = "  ← chosen" if abs(r["threshold"] - t) < 1e-9 else ""
            print(f"    {r['threshold']:.3f}     {r['precision']:.3f}     "
                  f"{r['recall']:.3f}   {r['f1']:.3f}   {r['false_positives']:>3}  "
                  f"{r['false_negatives']:>3}{mark}")
        if not any(abs(r["threshold"] - t) < 1e-9 for r in shown):
            print(f"    {chosen['threshold']:.3f}     {chosen['precision']:.3f}     "
                  f"{chosen['recall']:.3f}   {chosen['f1']:.3f}   "
                  f"{chosen['false_positives']:>3}  {chosen['false_negatives']:>3}  ← chosen")

        # ── breakdowns ───────────────────────────────────────────────────────
        print("\n" + "─" * 78)
        print("  BREAKDOWN AT CHOSEN THRESHOLD")
        print("─" * 78)
        for key, title in (("category", "by category"), ("style", "by EOB rendering")):
            rows_b = breakdown(observations, t, key)
            results[f"breakdown_{key}"] = rows_b
            print(f"\n    {title}")
            for r in rows_b:
                print(f"      {r[key]:<20} n={r['n']:<4} recall={r['recall']:.3f}  "
                      f"precision={r['precision']:.3f}")

        # ── latency ──────────────────────────────────────────────────────────
        lat = latency_report(observations)
        results["latency"] = lat
        print("\n" + "─" * 78)
        print("  LATENCY")
        print("─" * 78)
        e = lat["end_to_end_ms"]
        print(f"    end-to-end   p50={e['p50']} ms  p95={e['p95']} ms  p99={e['p99']} ms  "
              f"(n={lat['samples']}, first {WARMUP_QUERIES} discarded)")
        if "moss_engine_ms" in lat:
            me = lat["moss_engine_ms"]
            print(f"    Moss engine  p50={me['p50']} ms  p95={me['p95']} ms")
            print(f"    this layer's bridge overhead p50 = {lat['bridge_overhead_ms_p50']} ms")

        if not args.no_concurrency:
            conc = concurrent_latency(matcher, lines)
            results["concurrency"] = conc
            if "skipped" not in conc:
                print(f"\n    under load   {conc['threads']} threads, "
                      f"{conc['queries_issued']} queries")
                print(f"                 p50={conc['p50_ms']} ms  p95={conc['p95_ms']} ms  "
                      f"p99={conc['p99_ms']} ms  {conc['throughput_qps']} q/s")
                status = "intact" if conc["counter_intact"] else "LOST UPDATES"
                print(f"                 telemetry counters {status} "
                      f"({conc['counter_observed']}/{conc['counter_expected']})")
                if conc["errors"]:
                    print(f"                 errors: {conc['errors'][:3]}")

                single = lat["end_to_end_ms"]["p50"]
                if single and conc["p50_ms"] and conc["p50_ms"] > single * 2.5:
                    factor = conc["p50_ms"] / single
                    results["concurrency"]["serialisation_factor"] = round(factor, 1)
                    print(f"\n    ⚠  p50 rises {factor:.1f}x under {conc['threads']} threads.")
                    print("       All callers share ONE background event loop, so queries")
                    print("       serialise. Retrieval stays well inside the latency budget")
                    print("       per query, but a large batch pays them sequentially.")
                    print("       Mitigation if it ever binds: a small pool of loops, sized")
                    print("       to cores. Measured and reported rather than assumed away.")

    # ── document level ───────────────────────────────────────────────────────
    print("\n" + "─" * 78)
    print("  DOCUMENT-LEVEL DETECTION")
    print("─" * 78)
    doc_res = document_eval(docs, matcher, chosen["threshold"] if chosen else None)
    results["documents"] = doc_res
    for label, m in doc_res.items():
        line = (f"    {label:<12} precision={m['precision']:.3f}  recall={m['recall']:.3f}  "
                f"FN={m['false_negatives']}")
        if m["split_line_total"]:
            line += (f"   split-line offsets caught "
                     f"{m['split_line_detected']}/{m['split_line_total']}")
        print(line)
    if "with_moss" in doc_res and doc_res["with_moss"]["split_line_total"]:
        d = doc_res["with_moss"]
        if d["split_line_detected"] < d["split_line_total"]:
            print("\n    Note: offsets split across two lines (wording on one, amount on")
            print("    the next) are missed by design — the money gate skips amountless")
            print("    lines. Fix would be to carry a ±1-line amount lookahead into the")
            print("    gate. Reported rather than hidden.")

    print()
    if args.json_out:
        with open(args.json_out, "w") as fh:
            json.dump(results, fh, indent=2, default=str)
        print(f"  Full results → {args.json_out}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
